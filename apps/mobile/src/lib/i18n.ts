export type StringKey = keyof Strings;

const locale = getLocales()[0];
export const uiLanguage: 'en' | 'ar' = locale?.languageCode === 'ar' ? 'ar' : 'en';
const strings = uiLanguage === 'ar' ? ar : en;

/** Interface string, with {placeholders} filled in. */
export function t(key: StringKey, vars?: Record<string, string | number>): string {
  let s = strings[key];
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
  return s;
}

export const isRtlLayout = I18nManager.isRTL;

/** Language name in the interface language (falls back to the English name). */
export function languageName(code: string, englishName: string): string {
  try {
    const dn = new Intl.DisplayNames([uiLanguage], { type: 'language' });
    const name = dn.of(code === 'zh' ? 'zh-Hans' : code === 'zh-TW' ? 'zh-Hant' : code);
    if (name && name !== code) return uiLanguage === 'en' ? englishName : name;
  } catch {
    // Intl.DisplayNames is missing on some older Android engines.
  }
  return englishName;
}

export function formatDate(iso: string, withTime = false): string {
  const d = new Date(iso);
  return d.toLocaleString(uiLanguage === 'ar' ? 'ar' : undefined, {
    day: 'numeric',
    month: 'short',
    ...(withTime ? { hour: 'numeric', minute: '2-digit' } : { year: 'numeric' }),
  });
}
